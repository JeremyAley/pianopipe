class _Gen:
    def __init__(self, grade: int, seed: int, attempt: int = 0):
        self.g = GRADES[grade]
        self.rng = random.Random(f"sightread-{grade}-{seed}" + (f"-{attempt}" if attempt else ""))
        self.grade, self.seed = grade, seed

    # Keys and positions.

    def pitch(self, deg: int, alter: int = 0) -> int:
        """MIDI pitch of a scale degree: degree 0 is the tonic in the octave from C3."""
        return 48 + self.tonic + 12 * (deg // 7) + self.scale[deg % 7] + alter

    def degrees_from(self, lo_pitch: int, hi_pitch: int, allowed=None) -> list[int]:
        return [d for d in range(-14, 28) if lo_pitch <= self.pitch(d) <= hi_pitch and (allowed is None or d % 7 in allowed)]

    def pick_position(self, window: tuple[int, int], starts) -> int:
        """The lowest degree of a five-finger position whose first note is in `window`, starting on one of `starts`
        (scale degrees, 0 the tonic), nearest the window's middle."""
        cands = self.degrees_from(*window, starts)
        mid = (window[0] + window[1]) / 2
        cands.sort(key=lambda d: abs(self.pitch(d) - mid))
        best = [d for d in cands if abs(self.pitch(d) - mid) <= abs(self.pitch(cands[0]) - mid) + 3]
        return self.rng.choice(best)

    def fits(self, lo: int, hi: int, rng_: tuple[int, int], span: int) -> bool:
        """Degrees lo..hi inside a hand's pitch range and span, with room for a raised top note."""
        return rng_[0] <= self.pitch(lo) and self.pitch(hi) + 1 <= rng_[1] and self.pitch(hi) + 1 - self.pitch(lo) <= span

    # Rhythm.

    def bar_rhythm(self, length_beats: int, beat: Q, compound: bool, ending: str, first_bar: bool) -> list[tuple[Q, Q, bool]]:
        """(offset, duration, rest) in quarters for one bar. `ending`: "final" (a long last note), "phrase" (a held
        note, maybe with a rest after it) or ""."""
        g = self.g
        cells = [c for c in (COMPOUND_CELLS if compound else SIMPLE_CELLS) if c[1] <= self.grade]
        if not g.syncopation:
            cells = [c for c in cells if c[0] != "syn"]
        bar_len = beat * length_beats
        for _ in range(200):
            out, t = [], Q(0)
            # The last note: long, from a beat to the bar's end.
            if ending == "final":
                tail = self._final_tail(bar_len, beat, compound)
            elif ending == "phrase":
                tail = self._phrase_tail(bar_len, beat, compound)
            else:
                tail = []
            fill_to = bar_len - sum(abs(d) for d in tail)
            ok = True
            while t < fill_to:
                fit = [c for c in cells if sum(abs(Q(d)) for d in c[2]) <= fill_to - t and self._cell_ok(c, t, beat, bar_len, compound, first_bar)]
                if not fit:
                    ok = False
                    break
                c = self.rng.choices(fit, [w for *_, w in fit])[0]
                for d in c[2]:
                    d = Q(d)
                    out.append((t, abs(d), d < 0))
                    t += abs(d)
            if not ok or t != fill_to:
                continue
            for d in tail:
                d = Q(d)
                out.append((t, abs(d), d < 0))
                t += abs(d)
            if first_bar and out[0][2]:
                continue
            if sum(not r for *_, r in out) == 0 or sum(r for *_, r in out) > 1:
                continue  # at least a note, and at most one rest, in a bar
            return out
        return [(Q(0), bar_len, False)]

    def _cell_ok(self, c, t: Q, beat: Q, bar_len: Q, compound: bool, first_bar: bool) -> bool:
        name, _, durs, _ = c
        span = sum(abs(Q(d)) for d in durs)
        if t % beat:
            return False  # cells start on beats
        if first_bar and t == 0 and Q(durs[0]) < 0:
            return False
        if name == "w" and not (t == 0 and bar_len == 4):
            return False
        if name in ("dh",) and not compound and t != 0:
            return False
        if not compound and span == 2 and (t / beat) % 2 and self.grade < 3:
            return False
        if name == "syn" and (t / beat) % 2:
            return False
        if compound and name == "dh" and t != 0:
            return False
        if Q(durs[0]) < 0 and self.grade == 0 and t == 0:
            return False
        return True

    def _final_tail(self, bar_len: Q, beat: Q, compound: bool) -> list:
        if compound:
            return [bar_len] if self.rng.random() < 0.5 or bar_len == beat else [beat]  # the bar, or its last beat
        options = {Q(4): [[4], [2], [3]], Q(3): [[3], [2]], Q(2): [[2], [1]]}[bar_len]
        options = [o for o in options if o != [3] or self.grade >= 1]
        weights = [3, 2, 1][: len(options)]
        return [Q(d) for d in self.rng.choices(options, weights)[0]]

    def _phrase_tail(self, bar_len: Q, beat: Q, compound: bool) -> list:
        r = self.rng.random()
        if compound:
            return [beat] if r < 0.7 else [1, Q(-1, 2)]  # a dotted crotchet, or a crotchet and a breath
        if bar_len == 2:
            return [1] if r < 0.6 else [2]
        if r < 0.25:
            return [2, -1] if bar_len == 4 else [2]  # a held note and a breath
        if r < 0.45 and bar_len == 4:
            return [4] if self.grade < 1 or r < 0.35 else [3]
        return [2] if bar_len != 3 or r < 0.85 else [3]

    # The piece.

    def build(self) -> Piece:
        g, rng = self.g, self.rng
        self.key = rng.choice(g.keys)
        self.minor = self.key.endswith("m")
        self.tonic = PC[self.key.rstrip("m")]
        self.scale = MINOR if self.minor else MAJOR
        num, den = rng.choices([(n, d) for n, d, _ in g.metres], [w for *_, w in g.metres])[0]
        nbars = rng.choice(g.bars[(num, den)])
        compound = notation.compound(num, den)
        beat = notation.beat_length(num, den)
        beats = num // 3 if compound else num
        if (num, den) == (3, 8):
            beats = 1
        bar_len = beat * beats
        upbeat = Q(0)
        if g.upbeat and rng.random() < 0.3:
            upbeat = Q(1, 2) if compound else Q(1)
        phrases = _phrases(nbars)
        chords = self.harmony(phrases)
        # Each bar's rhythm; later phrases often take the first phrase's rhythm (but end as their own place asks).
        endings = []
        for p in phrases:
            endings += [""] * (p - 1) + ["phrase"]
        endings[-1] = "final"
        rhythms: list[list] = []
        first_len = phrases[0]
        for b in range(nbars):
            start_of_phrase = sum(phrases[: _phrase_index(phrases, b)])
            k = b - start_of_phrase
            if b >= first_len and k < first_len and endings[b] == endings[k] and rng.random() < 0.55:
                rhythms.append(list(rhythms[k]))
            else:
                rhythms.append(self.bar_rhythm(beats, beat, compound, endings[b], b == 0))
        tune = [[Ev(upbeat + b * bar_len + t, d, r, strong=(t == 0 or (beats == 4 and t == 2))) for t, d, r in rh]
                for b, rh in enumerate(rhythms)]
        if g.ties:
            self.tie(tune, endings)
        if g.hands_together:
            rh_ev, lh_ev, ranges = self.together(tune, chords, phrases, beat, bar_len, beats, compound, upbeat)
        else:
            rh_ev, lh_ev, ranges = self.separate(tune, chords, phrases)
        if upbeat:
            # One note before the first bar line, leading to the first downbeat: the fifth below or the leading tone.
            first = next(e for e in rh_ev if not e.rest and e.at >= upbeat)
            lo, hi = ranges["R"]
            opts = ([first.deg - 3] if first.deg % 7 == 0 else []) + [first.deg - 1, first.deg + 1]
            lead = next((d for d in opts if lo <= d <= hi), first.deg)
            raised = self.minor and lead % 7 == 6 and lead + 1 == first.deg
            rh_ev.insert(0, Ev(Q(0), upbeat, deg=lead, alter=1 if raised else 0))
        if g.chromatic:
            self.chromatic(rh_ev)
        if g.staccato:
            self.articulate(rh_ev, phrases, bar_len, upbeat)
        dyn = self.dynamics(phrases, upbeat)
        bpm_beat = rng.randint(*self._tempo(num, den, rh_ev))
        bpm = round(bpm_beat * (Q(3, 2) if compound else 1))
        notes = self.to_notes(rh_ev, "R", dyn, bar_len, upbeat) + self.to_notes(lh_ev, "L", dyn, bar_len, upbeat)
        notes = self.finger(notes, ranges, g.five_finger)
        meta = [(0, mido.MetaMessage("set_tempo", tempo=mido.bpm2tempo(bpm))),
                (0, mido.MetaMessage("key_signature", key=self.key))]
        if upbeat:
            meta.append((0, mido.MetaMessage("time_signature", numerator=int(upbeat * (den // 4) if den == 4 else upbeat * 2), denominator=den)))
        meta.append((int(upbeat * TPB), mido.MetaMessage("time_signature", numerator=num, denominator=den)))
        meta.sort(key=lambda e: e[0])
        word = _tempo_word(bpm_beat, compound, rng)
        return Piece(self.grade, self.seed, self.key, num, den, nbars, upbeat, bpm, word, notes,
                     [(i + (1 if upbeat else 0), m) for i, m in dyn], "together" if g.hands_together else "separate", meta)

    def _tempo(self, num: int, den: int, rh_ev: list[Ev]) -> tuple[int, int]:
        lo, hi = self.g.tempo
        if notation.compound(num, den) or (num, den) == (3, 8):
            lo, hi = round(lo * 0.62), round(hi * 0.62)  # a dotted quarter's
        shortest = min((e.dur for e in rh_ev if not e.rest), default=Q(1))
        if shortest < Q(1, 2):
            hi = lo + (hi - lo) // 3  # semiquavers: the slow end
        return lo, hi

    def harmony(self, phrases: list[int]) -> list[str]:
        """A chord per bar: phrases end on V (a half cadence), the last on V-I."""
        rng, out = self.rng, []
        rich = self.grade >= 4
        for i, p in enumerate(phrases):
            last = i == len(phrases) - 1
            if p == 2:
                out += rng.choice([["V", "I"], ["V", "I"], ["IV", "I"]] if last else [["I", "V"], ["IV", "V"]])
            else:
                if last:
                    opts = [["I", "IV", "V", "I"], ["I", "V", "V", "I"], ["I", "IV", "I", "I"]]
                    if rich:
                        opts += [["I", "ii", "V", "I"], ["vi", "IV", "V", "I"]]
                else:
                    opts = [["I", "IV", "I", "V"], ["I", "V", "I", "V"], ["I", "I", "IV", "V"]]
                    if rich:
                        opts += [["I", "vi", "ii", "V"], ["I", "vi", "IV", "V"]]
                out += rng.choice(opts)
        if out and out[0] != "I":
            out[0] = "I"
        return out

    def tie(self, tune: list[list[Ev]], endings: list[str]) -> None:
        """From Grade 3: now and then a bar's last note is tied over into the next bar (inside a phrase)."""
        for b in range(len(tune) - 2):
            last, nxt = tune[b][-1], tune[b + 1][0]
            if endings[b] or last.rest or nxt.rest or len(tune[b + 1]) < 2 or self.rng.random() > 0.15:
                continue
            if nxt.dur > 1 or last.dur > 2:
                continue
            last.dur += nxt.dur
            last.tied = True
            tune[b + 1].pop(0)

    def melody(self, events: list[Ev], chords_at, lo: int, hi: int, start=None, cadence: str = "") -> None:
        """Degrees for the notes of `events` (in place), within lo..hi. `chords_at(ev)` is the chord sounding there.
        `cadence`: "final" ends on the tonic approached by step, "half" on a note of V, "" anywhere."""
        rng, g = self.rng, self.g
        notes = [e for e in events if not e.rest]
        if not notes:
            return
        tonics = [d for d in range(lo, hi + 1) if d % 7 == 0]
        goal = min(tonics, key=lambda d: abs(d - (lo + hi) / 2 + 1)) if tonics else lo
        prev = start
        last_dir, leaps = 0, 0
        for i, e in enumerate(notes):
            remaining = len(notes) - i - 1
            chord = _triad(chords_at(e))
            if prev is None:
                pool = [d for d in range(lo, hi + 1) if d % 7 in ((0, 2, 4) if self.grade else (0, 2, 4))]
                pool.sort(key=lambda d: abs(d - goal))
                e.deg = pool[0] if self.grade == 0 and rng.random() < 0.6 else rng.choice(pool[:3])
            elif cadence == "final" and remaining == 0:
                e.deg = min(tonics, key=lambda d: abs(d - prev)) if tonics else prev
            elif cadence == "final" and remaining == 1 and tonics:
                end = min(tonics, key=lambda d: abs(d - prev))
                near = [d for d in (end + 1, end - 1, end + 4 - 7 * (end + 4 > hi))
                        if lo <= d <= hi and abs(d - prev) <= g.leap and abs(d - end) <= g.leap]
                # Else any note within reach of both the last one and a tonic (the final note mustn't leap further).
                near = near or sorted((d for d in range(lo, hi + 1) if abs(d - prev) <= g.leap
                                       and min(abs(d - t) for t in tonics) <= g.leap),
                                      key=lambda d: min(abs(d - t) for t in tonics))
                e.deg = rng.choice(near[:2]) if near else prev
            elif cadence == "half" and remaining == 0:
                vs = [d for d in range(lo, hi + 1) if d % 7 in (4, 6, 1) and abs(d - prev) <= g.leap]
                e.deg = min(vs, key=lambda d: (abs(d - prev), rng.random())) if vs else prev
            else:
                e.deg = self.step(prev, lo, hi, chord if e.strong else None, last_dir, leaps)
                # Head for the cadence's note in the last few notes.
                if cadence == "final" and 1 < remaining <= 3 and tonics and abs(e.deg - goal) > 2 * (remaining - 1) + 1:
                    e.deg = prev + (1 if goal > prev else -1)
            if prev is not None:
                mv = e.deg - prev
                leaps = leaps + 1 if abs(mv) >= 2 else 0
                last_dir = (mv > 0) - (mv < 0)
            prev = e.deg

    def step(self, prev: int, lo: int, hi: int, chord, last_dir: int, leaps: int) -> int:
        rng, g = self.rng, self.g
        weights = {0: 0.12, 1: 0.55, 2: 0.25, 3: 0.05, 4: 0.05, 5: 0.02, 7: 0.02}
        best, best_w = [], []
        for size, w in weights.items():
            if size > g.leap or (leaps >= 2 and size >= 2):
                continue
            for sign in ((1,) if size == 0 else (1, -1)):
                d = prev + sign * size
                if not lo <= d <= hi:
                    continue
                if abs(self.pitch(d) - self.pitch(prev)) == 6:
                    continue  # no tritone leaps
                ww = w
                if size >= 2 and sign == last_dir:
                    ww *= 0.5  # after a leap, more often back the other way
                if chord is not None:
                    ww *= 3 if d % 7 in chord else 0.25
                best.append(d)
                best_w.append(ww)
        return rng.choices(best, best_w)[0] if best else prev

    def separate(self, tune, chords, phrases):
        """Hands separately: phrases go to one hand or the other (or all to one); the other hand rests."""
        g, rng = self.g, self.rng
        starts = (0,) if self.grade == 0 else (0, 3, 4)
        for _ in range(20):  # two positions that don't overlap
            rh_lo = self.pick_position((g.rh[0], g.rh[0] + 9), starts)
            lh_lo = self.pick_position((g.lh[0], g.lh[0] + 9), starts)
            if self.pitch(lh_lo + 4) < self.pitch(rh_lo):
                break
        ranges = {"R": (rh_lo, rh_lo + 4), "L": (lh_lo, lh_lo + 4)}
        n = len(phrases)
        mode = rng.choices(["share", "rh", "lh"], [0.65, 0.22, 0.13] if self.grade == 0 else [0.75, 0.15, 0.1])[0]
        if mode == "share":
            first = rng.choice("RL") if self.grade else "R"
            hands = [first if i % 2 == 0 else ("L" if first == "R" else "R") for i in range(n)]
            if n >= 3 and rng.random() < 0.4:
                hands[-1] = first if hands[-1] != first else hands[-1]
        else:
            hands = ["R" if mode == "rh" else "L"] * n
        rh_ev, lh_ev = [], []
        bar = 0
        prev_deg = {"R": None, "L": None}
        for i, p in enumerate(phrases):
            evs = [e for b in range(bar, bar + p) for e in tune[b]]
            h = hands[i]
            lo, hi = ranges[h]
            cad = "final" if i == n - 1 else "half"
            start = None if prev_deg[h] is None else prev_deg[h]
            bars_of = {id(e): b for b in range(bar, bar + p) for e in tune[b]}
            self.melody(evs, lambda e: chords[bars_of[id(e)]], lo, hi, start, cad)
            (rh_ev if h == "R" else lh_ev).extend(evs)
            last = [e for e in evs if not e.rest]
            if last:
                prev_deg[h] = last[-1].deg
            bar += p
        return rh_ev, lh_ev, ranges

    def together(self, tune, chords, phrases, beat, bar_len, beats, compound, upbeat):
        """Hands together: the tune in the right hand, an accompaniment in the left."""
        g, rng = self.g, self.rng
        if g.five_finger:
            rh_lo = self.pick_position((g.rh[0], g.rh[0] + 11), (0, 3, 4))
            lh_lo = self.pick_position((g.lh[0], g.lh[0] + 10), (0,))
            while self.pitch(rh_lo) - self.pitch(lh_lo + 4) < 3:
                lh_lo -= 7
            ranges = {"R": (rh_lo, rh_lo + 4), "L": (lh_lo, lh_lo + 4)}
        else:
            width = {3: 7, 4: 9, 5: 11}[self.grade]
            rh_lo = self.pick_position((g.rh[0] + 2, g.rh[0] + 12), (0, 4, 2))
            while not self.fits(rh_lo, rh_lo + width, g.rh, g.span) and width > 5:
                width -= 1
            lh_w = {3: 7, 4: 7, 5: 9}[self.grade]
            lh_lo = self.pick_position((g.lh[0] + 4, g.lh[0] + 14), (0, 4, 3))
            while self.pitch(lh_lo + lh_w) + 1 > g.lh[1] or self.pitch(lh_lo + lh_w) >= self.pitch(rh_lo):
                lh_w -= 1
                if lh_w < 4:
                    lh_lo -= 7
                    lh_w = {3: 7, 4: 7, 5: 9}[self.grade]
            ranges = {"R": (rh_lo, rh_lo + width), "L": (lh_lo, lh_lo + lh_w)}
        rh_ev = []
        bar, prev = 0, None
        for i, p in enumerate(phrases):
            evs = [e for b in range(bar, bar + p) for e in tune[b]]
            bars_of = {id(e): b for b in range(bar, bar + p) for e in tune[b]}
            cad = "final" if i == len(phrases) - 1 else "half"
            # A later phrase sometimes repeats the first one's tune (A A'), ending as its own cadence asks.
            notes = [e for e in evs if not e.rest]
            if i > 0 and phrases[i] == phrases[0] and len(notes) > 2 and rng.random() < 0.3 and \
                    self._copy(evs, rh_ev[: len(evs)]):
                self.melody(notes[-2:], lambda e: chords[bars_of[id(e)]], *ranges["R"], notes[-3].deg, cad)
            else:
                self.melody(evs, lambda e: chords[bars_of[id(e)]], *ranges["R"], prev, cad)
            rh_ev.extend(evs)
            notes = [e for e in evs if not e.rest]
            prev = notes[-1].deg if notes else prev
            bar += p
        self.minor_leading(rh_ev)
        lh_ev = self.accompany(chords, tune, ranges["L"], beat, bar_len, beats, compound, upbeat)
        return rh_ev, lh_ev, ranges

    def _copy(self, evs: list[Ev], src: list[Ev]) -> bool:
        """The first phrase's degrees onto a phrase with the same rhythm; False (nothing changed) if they differ."""
        if len(evs) != len(src) or any(a.rest != b.rest or a.dur != b.dur for a, b in zip(evs, src)):
            return False
        for a, b in zip(evs, src):
            a.deg = b.deg
        return True

    def minor_leading(self, evs: list[Ev]) -> None:
        """In a minor key, the seventh degree raised where it leads to the tonic (harmonic minor); after the sixth, the
        sixth is raised too (melodic minor: no augmented second) from Grade 3, and before it the seventh stays."""
        if not self.minor:
            return
        notes = [e for e in evs if not e.rest]
        for i, (a, b) in enumerate(zip(notes, notes[1:])):
            if a.deg % 7 == 6 and b.deg == a.deg + 1:
                before = notes[i - 1] if i else None
                if before is not None and before.deg == a.deg - 1:
                    if self.grade < 3:
                        continue
                    before.alter = 1
                a.alter = 1

    def accompany(self, chords, tune, lrange, beat, bar_len, beats, compound, upbeat) -> list[Ev]:
        g, rng = self.g, self.rng
        lo, hi = lrange
        out: list[Ev] = []
        prev_root = None
        n = len(chords)
        for b, ch in enumerate(chords):
            t0 = upbeat + b * bar_len
            root = TRIADS[ch]
            cands = [d for d in range(lo, hi + 1) if d % 7 == root % 7]
            if not cands:  # a root outside the hand's reach: its fifth or third
                cands = [d for d in range(lo, hi + 1) if d % 7 in _triad(ch)]
            # Nearest the last root, with room for its fifth above where the hand's range has it.
            r = min(cands, key=lambda d: ((abs(d - prev_root) if prev_root is not None else abs(d - lo - 1))
                                          + (3 if d + 4 > hi else 0), d))
            prev_root = r
            busy = sum(not e.rest for e in tune[b]) >= 6 or any(e.dur < Q(1, 2) for e in tune[b])
            last = b == n - 1
            fifth = r + 4 if r + 4 <= hi else (r - 3 if r - 3 >= lo else r)
            third = r + 2 if r + 2 <= hi else r
            pats = self._lh_patterns(bar_len, beat, beats, compound, busy or last, close=r + 4 <= hi)
            if last:  # the last bar: the tonic held, alone or under its fifth or third
                pats = [p for p in pats if p[0] == "bar" or (p[0] == "dyad" and fifth > r and third > r)]
            pat = rng.choices(pats, [w for _, _, w in pats])[0][1]
            for t, d, which in pat:
                degs = list(dict.fromkeys({0: r, 4: fifth, 2: third}[x] for x in which))  # a third with no room is r
                alters = [1 if self.minor and ch == "V" and x % 7 == 6 else 0 for x in degs]  # V's raised leading tone
                out.append(Ev(t0 + t, d, deg=degs[0], alter=alters[0], extra=tuple(degs[1:]), extra_alter=tuple(alters[1:])))
        return out

    def _lh_patterns(self, bar_len, beat, beats, compound, plain: bool, close: bool = True):
        """(name, [(offset, duration, which chord notes: 0 root, 2 third, 4 fifth)], weight) for a bar. `plain`: only
        held notes and chords (the right hand is busy, or the last bar); without `close` (no fifth above the root in
        the hand's range) no figures that would leap about."""
        G = self.grade
        plain = plain or not close
        bar = ("bar", [(Q(0), bar_len, (0,))], 3.0)
        if compound:
            one = [bar]
            if beats == 2:
                one.append(("dq2", [(Q(0), beat, (0,)), (beat, beat, (4,))], 2.0))
            if G >= 4 and self.g.dyads:
                one.append(("dyad", [(Q(0), bar_len, (0, 4))], 2.0))
                if beats == 2:
                    one.append(("dyad2", [(Q(0), beat, (0, 4)), (beat, beat, (0, 2))], 1.5))
            if G >= 5 and not plain:
                one.append(("broken", [(i * Q(1, 2), Q(1, 2), ((0,), (4,), (2,))[i % 3]) for i in range(beats * 3)], 2.5))
            return one
        pats = []
        if bar_len in (2, 3, 4):
            pats.append(bar)
        if bar_len == 4:
            pats.append(("halves", [(Q(0), Q(2), (0,)), (Q(2), Q(2), (4,))], 2.0))
        if bar_len == 3:
            pats.append(("h+q", [(Q(0), Q(2), (0,)), (Q(2), Q(1), (4,))], 1.0 if G >= 2 else 0))
        if G >= 3 and not plain:
            qs = [(Q(i), Q(1), ((0,), (4,), (2,), (4,))[i % 4]) for i in range(int(bar_len))]
            pats.append(("quarters", qs, 1.5))
        if G >= 4 and self.g.dyads:
            pats.append(("dyad", [(Q(0), bar_len, (0, 4) if self.rng.random() < 0.6 else (0, 2))], 2.0))
            if bar_len == 4:
                pats.append(("dyads", [(Q(0), Q(2), (0, 4)), (Q(2), Q(2), (0, 2))], 1.5))
        if G >= 5 and not plain:
            n = int(bar_len * 2)
            pats.append(("broken", [(i * Q(1, 2), Q(1, 2), ((0,), (4,), (2,), (4,))[i % 4]) for i in range(n)], 2.5))
        return [p for p in pats if p[2] > 0]

    def chromatic(self, evs: list[Ev]) -> None:
        """Grade 5: a raised lower neighbour (G F# G) or two, where the tune steps down a whole tone and back."""
        notes = [e for e in evs if not e.rest]
        done = 0
        for a, b, c in zip(notes, notes[1:], notes[2:]):
            if done >= 2:
                break
            if a.deg == c.deg and b.deg == a.deg - 1 and not b.strong and b.dur <= 1 and \
                    self.pitch(a.deg) - self.pitch(b.deg) == 2 and self.rng.random() < 0.7:
                b.alter = 1
                done += 1

    def articulate(self, evs: list[Ev], phrases, bar_len, upbeat) -> None:
        """From Grade 3: a phrase now and then played staccato (its crotchets and quavers short)."""
        bar = 0
        # Only a note the next one follows straight on: before a rest the short note would be written as its length.
        starts = {e.at for e in evs if not e.rest}
        for p in phrases:
            if self.rng.random() < 0.25:
                a, b = upbeat + bar * bar_len, upbeat + (bar + p) * bar_len
                for e in evs:
                    if a <= e.at < b and not e.rest and e.dur in (1, Q(1, 2)) and not e.tied and e.at + e.dur in starts:
                        e.staccato = True
            bar += p

    def dynamics(self, phrases, upbeat) -> list[tuple[int, str]]:
        """A marking at the start; from Grade 2 often a change where a phrase starts."""
        rng = self.rng
        marks = ["p", "mf", "f"] if self.grade < 2 else ["p", "mp", "mf", "f"]
        first = rng.choice(marks)
        out = [(0, first)]
        if self.grade >= 2 and len(phrases) > 1 and rng.random() < 0.6:
            at = sum(phrases[: rng.randrange(1, len(phrases))])
            out.append((at, rng.choice([m for m in marks if m != first])))
        return out

    def to_notes(self, evs: list[Ev], hand: str, dyn, bar_len: Q, upbeat: Q) -> list[Note]:
        out = []
        for e in evs:
            if e.rest:
                continue
            bar = max(0, int((e.at - upbeat) // bar_len))
            mark = [m for b, m in dyn if b <= bar][-1]
            vel = DYNAMICS[mark] + (6 if e.strong else 0)
            dur = e.dur
            if e.staccato:
                dur = Q(3, 8) if e.dur == 1 else Q(1, 8)  # written back as the value with a dot (notation._staccato)
            start, end = int(e.at * TPB), int((e.at + dur) * TPB)
            for d, alter in zip((e.deg,) + e.extra, (e.alter,) + (e.extra_alter or (0,) * len(e.extra))):
                out.append(Note(start, end, self.pitch(d, alter), vel, hand))
        return out

    def finger(self, notes: list[Note], ranges, five_finger: bool) -> list[Note]:
        """Every note's finger. In a five-finger position the finger is the key's place in it; otherwise fingering.py
        chooses. The sheet prints a hand's first finger and each one where the hand moves (Note.printed)."""
        if five_finger:
            out = []
            for n in notes:
                lo = ranges[n.hand][0]
                # The position's five keys, by pitch (a raised note keeps its degree's finger).
                keys = [self.pitch(lo + k) for k in range(5)]
                k = min(range(5), key=lambda i: abs(keys[i] - n.pitch))
                out.append(replace(n, finger=k + 1 if n.hand == "R" else 5 - k))
            notes = out
        else:
            notes = assign_fingering(notes, TPB)
        return _mark_printed(notes)


# Where each finger usually sits above the thumb, in semitones, in a hand at rest over five keys.
_FINGER_OFFSET = {1: 0, 2: 2, 3: 4, 4: 5, 5: 7}


def _mark_printed(notes: list[Note]) -> list[Note]:
    """Printed fingers: each hand's first note, its first after a rest of a bar of 4/4 or more, and a note where the
    hand's position moves (the thumb's place it implies is a minor third or more from the note before's)."""
    out = []
    for hand in ("R", "L"):
        prev_anchor, last_end = None, None
        hn = sorted((n for n in notes if n.hand == hand), key=lambda n: (n.start, -n.pitch))
        seen_onsets = set()
        for n in hn:
            # A chord's notes: only its top note carries the print decision.
            off = _FINGER_OFFSET[n.finger]
            anchor = n.pitch - off if hand == "R" else n.pitch + off
            entry = last_end is None or n.start - last_end >= 4 * TPB
            first_of_onset = n.start not in seen_onsets
            seen_onsets.add(n.start)
            moved = prev_anchor is not None and abs(anchor - prev_anchor) >= 3 and first_of_onset
            out.append(replace(n, printed=first_of_onset and (prev_anchor is None or entry or moved)))
            if first_of_onset:
                prev_anchor = anchor
            last_end = max(last_end or 0, n.end)
    out.sort(key=lambda n: (n.start, n.hand, n.pitch))
    return out


_WHITE = [0, 0, 1, 1, 2, 3, 3, 4, 4, 5, 5, 6]  # a key's white-key step in its octave (a black key: the one below)


def _white(pitch: int) -> int:
    return 7 * (pitch // 12) + _WHITE[pitch % 12]


def _triad(chord: str) -> tuple[int, int, int]:
    r = TRIADS[chord]
    return (r % 7, (r + 2) % 7, (r + 4) % 7)


def _phrases(bars: int) -> list[int]:
    """Bars per phrase: twos up to 6 bars, then fours with a two in the middle where it doesn't divide."""
    if bars <= 6:
        return [2] * (bars // 2)
    fours, rest = divmod(bars, 4)
    out = [4] * fours
    if rest:
        out.insert(len(out) // 2 + (1 if len(out) > 1 else 0) - (1 if len(out) == 2 else 0), rest)
    return out


def _phrase_index(phrases: list[int], bar: int) -> int:
    total = 0
    for i, p in enumerate(phrases):
        total += p
        if bar < total:
            return i
    return len(phrases) - 1


_WORDS = (  # (up to this many beats a minute, tempo words)
    (76, ("Andante", "Andantino", "Gently")),
    (92, ("Moderato", "Steadily", "Andante con moto")),
    (200, ("Allegretto", "Allegro moderato", "Brightly")),
)
_WORDS_COMPOUND = ((52, ("Andante", "Gently")), (60, ("Moderato", "Andantino")), (200, ("Allegretto", "Lightly")))


def _tempo_word(bpm_beat: int, compound: bool, rng: random.Random) -> str:
    for limit, words in (_WORDS_COMPOUND if compound else _WORDS):
        if bpm_beat <= limit:
            return rng.choice(words)
    return "Moderato"


def generate(grade: int, seed: int) -> Piece:
    """A sight-reading piece at `grade` (0 Initial to 5); the same seed always gives the same piece."""
    if grade not in GRADES:
        raise ValueError(f"grade {grade} is not one of {', '.join(map(str, GRADES))}")
    # A draw that strays outside the parameters (a range the positions can't fit, a value that would need a tie) is
    # drawn again from the seed's next stream.
    for attempt in range(40):
        piece = _Gen(grade, seed, attempt).build()
        if not problems(piece):
            return piece
    raise RuntimeError(f"grade {grade} seed {seed}: no piece inside the grade's parameters ({problems(piece)})")


# --- checks ----------------------------------------------------------------------------------------------------------


def problems(piece: Piece) -> list[str]:
    """What in a piece is outside its grade's parameters (empty when it's inside): key, metre, length, pitch range and
    span per hand, the hands' overlap (hands separately), five-finger positions, the written note values and ties."""
    g = GRADES[piece.grade]
    out = []
    if piece.key not in g.keys:
        out.append(f"key {piece.key}")
    if (piece.num, piece.den) not in g.bars:
        out.append(f"time {piece.time}")
    elif piece.bars not in g.bars[(piece.num, piece.den)]:
        out.append(f"{piece.bars} bars")
    if piece.upbeat and not g.upbeat:
        out.append("an upbeat")
    for hand, (lo, hi) in (("R", g.rh), ("L", g.lh)):
        ps = [n.pitch for n in piece.notes if n.hand == hand]
        if not ps:
            continue
        if min(ps) < lo or max(ps) > hi:
            out.append(f"{hand} range {min(ps)}-{max(ps)} outside {lo}-{hi}")
        if max(ps) - min(ps) > g.span:
            out.append(f"{hand} spans {max(ps) - min(ps)} semitones")
        if g.five_finger:
            fingers = {n.finger for n in piece.notes if n.hand == hand}
            keys = sorted({_white(p) for p in ps})
            if keys[-1] - keys[0] > 4 or not fingers <= {1, 2, 3, 4, 5}:
                out.append(f"{hand} leaves its five-finger position")
    if not g.hands_together:
        r = [(n.start, n.end) for n in piece.notes if n.hand == "R"]
        for n in piece.notes:
            if n.hand == "L" and any(a < n.end and n.start < b for a, b in r):
                out.append("hands overlap")
                break
    if not g.dyads:
        starts = [(n.hand, n.start) for n in piece.notes]
        if len(starts) != len(set(starts)):
            out.append("a chord")
    keys = [(n.hand, n.start, n.pitch) for n in piece.notes]
    if len(keys) != len(set(keys)):
        out.append("a key struck twice at once")
    # The tune's leaps (in scale steps, between its top notes; both hands' when they take turns).
    for hand in ("R", "L") if not g.hands_together else ("R",):
        tops: dict[int, int] = {}
        for n in piece.notes:
            if n.hand == hand:
                tops[n.start] = max(tops.get(n.start, 0), n.pitch)
        line = [tops[t] for t in sorted(tops)]
        if any(abs(_white(a) - _white(b)) > g.leap for a, b in zip(line, line[1:])):
            out.append(f"{hand} leaps more than {g.leap} steps")
    if not any(n.hand == "R" for n in piece.notes) and not any(n.hand == "L" for n in piece.notes):
        out.append("no notes")
    xml = written(piece)
    types = set(re.findall(r"<type>(\w+)</type>((?:<dot/>)?)", xml))
    values = {(t, len(d) // 6) for t, d in types}
    if not values <= g.values:
        out.append(f"note values {sorted(values - g.values)}")
    if "<tie " in xml and not g.ties:
        out.append("a tie")
    # The tune's last note (the right hand's top) and the bass under it (the left hand's lowest) are the tonic.
    end = max(n.start for n in piece.notes)
    for hand in ("R", "L"):
        last = [n.pitch for n in piece.notes if n.hand == hand and n.end > end]
        if last and ((max(last) if hand == "R" else min(last)) - piece_tonic(piece)) % 12:
            out.append(f"{hand} doesn't end on the tonic")
    return out


def piece_tonic(piece: Piece) -> int:
    return PC[piece.key.rstrip("m")]


def written(piece: Piece) -> str:
    """The piece's notation as MusicXML (what the sheet shows), without engraving it."""
    import tempfile

    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "level1.mid"
        midi_io.write_app_midi(path, TPB, piece.meta, piece.notes)
        song = midi_io.load(path)
    return notation.to_musicxml(notation.build(song, 1), fingering=False)


# --- the bank (the reading collection) -------------------------------------------------------------------------------


def grade_name(grade: int) -> str:
    """Our scale's name for a grade (learning-mode.md §1.5): "Initial" for 0."""
    return "Initial" if grade == 0 else f"Grade {grade}"


def piece_id(grade: int, number: int) -> str:
    return f"sr-g{grade}-{number:03d}"


def bank_seeds(grade: int, count: int) -> list[int]:
    """Seeds for the bank's `count` pieces at a grade: 1, 2, 3, ... skipping any that repeat an earlier piece's notes."""
    seen, seeds, seed = set(), [], 0
    while len(seeds) < count:
        seed += 1
        fp = generate(grade, seed).fingerprint()
        if fp not in seen:
            seen.add(fp)
            seeds.append(seed)
    return seeds


def build_piece(grade: int, seed: int, number: int, out_dir: str | Path, sheets: bool = True) -> dict:
    """One bank piece: songs/<id>/level1.mid (and its sheet) under out_dir; returns its catalog entry as a dict."""
    piece = generate(grade, seed)
    pid = piece_id(grade, number)
    song_dir = Path(out_dir) / "songs" / pid
    title = f"{grade_name(grade)} sight-reading {number}"
    sheet = piece.write(song_dir, "level1", f"{LABEL} {number}", sheet=sheets)
    path = song_dir / "level1.mid"
    notes = piece.notes
    seconds = tempo_map(midi_io.load(path))
    # The key is the one the piece was written in, not a guess from its notes (a short tune in G can look like E minor).
    skills = [k if not k.startswith("key:") else f"key:{piece.key}" for k in features.skills(notes, seconds, TPB, piece.meta)]
    lv = Level(1, LABEL, f"songs/{pid}/level1.mid", sha256_file(path), len(notes),
               difficulty_score(notes, seconds, TPB), True, float(grade), "reference", piece.bpm, skills)
    if sheet is not None:
        lv.sheet = SheetRef(f"songs/{pid}/level1.sheet.json", sheet.sha256, sheet.pages)
    entry = SongEntry(
        id=pid, title=title, full_title=f"{title} ({piece.key_name}, {piece.time})", composer="Quest Piano Trainer",
        license=LICENSE, attribution=f"Generated by pianopipe sightread --grade {grade} --seed {seed}",
        hand_source="generated", duration_s=round(seconds(max(n.end for n in notes)), 2), levels=[lv],
        tags=[grade_tag(float(grade)), "sight-reading", f"hands-{piece.hands}"],
        character=features.character(notes, seconds, TPB),
    )
    return asdict(entry)


def _build_one(args) -> dict:
    return build_piece(*args)


def build_bank(out_dir: str | Path, count: int = 200, grades=tuple(GRADES), sheets: bool = True, jobs: int | None = None,
               name: str = "Quest Piano Trainer reading", log=print) -> Catalog:
    """The reading collection: `count` pieces per grade under out_dir (catalog.json, songs/<id>/...). Each piece is
    built in a worker process (Verovio is native code: a crash costs one try of one piece, which is retried)."""
    out_dir = Path(out_dir)
    jobs = jobs or max(1, (os.cpu_count() or 2) - 1)
    tasks = []
    for grade in grades:
        seeds = bank_seeds(grade, count)
        tasks += [(grade, seed, number, str(out_dir), sheets) for number, seed in enumerate(seeds, 1)]
    if (out_dir / "songs").exists():
        import shutil

        shutil.rmtree(out_dir / "songs")
    done: dict[tuple[int, int], dict] = {}
    tries = {t[:3]: 0 for t in tasks}
    todo = list(tasks)
    while todo:
        failed = []
        try:
            with ProcessPoolExecutor(max_workers=jobs) as pool:
                futures = {pool.submit(_build_one, t): t for t in todo}
                for fut in as_completed(futures):
                    t = futures[fut]
                    try:
                        done[(t[0], t[2])] = fut.result()
                        if len(done) % 100 == 0:
                            log(f"  {len(done)} of {len(tasks)} pieces")
                    except BrokenProcessPool:
                        failed.append(t)
                    except Exception as exc:  # noqa: BLE001 - retried, then reported
                        log(f"  {piece_id(t[0], t[2])} (seed {t[1]}): {exc}")
                        failed.append(t)
        except BrokenProcessPool:
            failed = [t for t in todo if (t[0], t[2]) not in done]
        todo = []
        for t in failed:
            tries[t[:3]] += 1
            if tries[t[:3]] < 3:
                todo.append(t)
            else:
                raise RuntimeError(f"{piece_id(t[0], t[2])} (seed {t[1]}) failed three times")
    songs = [_entry(done[(t[0], t[2])]) for t in tasks]
    Catalog(name, songs, collection=COLLECTION).save(out_dir / "catalog.json")
    return Catalog.load(out_dir / "catalog.json")  # validated


def _entry(d: dict) -> SongEntry:
    """A catalog entry back from build_piece's dict (it crosses a process boundary as one)."""
    levels = [Level(**{**lv, "sheet": SheetRef(**lv["sheet"]) if lv["sheet"] else None}) for lv in d["levels"]]
    return SongEntry(**{**d, "levels": levels})


def summary(cat: Catalog) -> str:
    """Counts per grade: keys, metres, hands, pages and size."""
    lines = []
    by_grade: dict[int, list[SongEntry]] = {}
    for s in cat.songs:
        by_grade.setdefault(int(s.levels[0].grade or 0), []).append(s)
    for grade, songs in sorted(by_grade.items()):
        keys: dict[str, int] = {}
        times: dict[str, int] = {}
        for s in songs:
            for k in s.levels[0].skills:
                if k.startswith("key:"):
                    keys[k[4:]] = keys.get(k[4:], 0) + 1
                if k.startswith("time:"):
                    times[k[5:]] = times.get(k[5:], 0) + 1
        lines.append(f"grade {grade}: {len(songs)} pieces; keys " + ", ".join(f"{k} {v}" for k, v in sorted(keys.items()))
                     + "; time " + ", ".join(f"{k} {v}" for k, v in sorted(times.items())))
    return "\n".join(lines)
