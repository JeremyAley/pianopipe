"""Sight-reading pieces generated at a grade (docs/learning-mode.md §12.3, §14 L7): short pieces, never seen before,
inside the grade's parameters (§12.2 and §1.2: keys, metres, note values, length, hand position and range), written
as app-ready levels with their sheet music. The reading collection (docs/formats.md, "The reading collection") is a
bank of them per grade.

A piece is built in scale degrees: phrases of two or four bars over a plan of I, IV and V (ii and vi from Grade 4),
each bar's rhythm drawn from the cells its grade allows (a phrase often repeats the first one's rhythm), a melody that
moves mostly by step with chord tones on strong beats, a half cadence at the end of a phrase and the tonic, approached
by step, at the end. Initial and Grade 1 share the tune between the hands (hands separately); from Grade 2 the left
hand accompanies: single notes, then quarter patterns, two-note chords (Grade 4) and broken chords (Grade 5). Grades 0-2
stay in one five-finger position per hand, so every finger follows from the position; from Grade 3 the hands move
(fingering.py fingers them). The same grade and seed always give the same piece, notes and pages.

`GRADES` is the table the tests check; `generate(grade, seed)` makes one piece, `Piece.write` its level file and
sheet, `engrave_level` engraves any short level the same way (the reading cards and dictation reuse it, §14 L8, L16).
"""

