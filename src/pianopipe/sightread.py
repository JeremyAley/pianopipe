@dataclass
class Ev:
    """One written note or rest of a hand, in quarters from the piece's start (after any upbeat)."""
    at: Q
    dur: Q
    rest: bool = False
    deg: int = 0  # scale degree from the tonic (any octave: 7 is the tonic an octave up)
    alter: int = 0  # semitones: a raised leading tone or a chromatic note
    extra: tuple[int, ...] = ()  # more degrees sounding with it (a two-note chord)
    extra_alter: tuple[int, ...] = ()  # their alterations
    staccato: bool = False
    strong: bool = False
    tied: bool = False  # lengthened over the bar line (written as a tie)


@dataclass
class Piece:
    grade: int
    seed: int
    key: str
    num: int
    den: int
    bars: int  # full bars, not counting an upbeat
    upbeat: Q  # quarters before the first bar line (0 for none)
    bpm: int  # quarters a minute
    tempo_word: str
    notes: list[Note]
    dynamics: list[tuple[int, str]]  # (measure index, counting an upbeat measure, marking)
    hands: str  # "separate" or "together"
    meta: list = field(default_factory=list)

    @property
    def minor(self) -> bool:
        return self.key.endswith("m")

    @property
    def key_name(self) -> str:
        tonic = self.key.rstrip("m")
        return f"{KEY_NAMES.get(tonic, tonic)} {'minor' if self.minor else 'major'}"

    @property
    def time(self) -> str:
        return f"{self.num}/{self.den}"

    def fingerprint(self) -> str:
        return hashlib.sha256(repr(sorted((n.start, n.end, n.pitch, n.hand) for n in self.notes)).encode()).hexdigest()

    def write(self, out_dir: str | Path, stem: str = "level1", title: str = "", sheet: bool = True):
        """Writes out_dir/<stem>.mid and, with `sheet`, its pages and sheet.json. Returns the engrave.Sheet or None."""
        out_dir = Path(out_dir)
        midi_io.write_app_midi(out_dir / f"{stem}.mid", TPB, self.meta, self.notes)
        if not sheet:
            return None
        return engrave_level(out_dir / f"{stem}.mid", out_dir, stem, title or f"{LABEL} {self.seed}",
                             f"{grade_name(self.grade)} · {LABEL}", self.tempo_word, self.dynamics)


def engrave_level(level_midi: str | Path, out_dir: str | Path, stem: str, title: str, subtitle: str,
                  tempo: str = "", dynamics: list[tuple[int, str]] = (), level: int = 1) -> "engrave.Sheet":
    """Engraves a short app-ready level as a sight-reading page: one line per hand, finger numbers only where they are
    printed (Note.printed: a hand's first note and where it moves), dynamics at the measures given, the title block
    with `subtitle` under the title and the tempo word. Writes out_dir/<stem>.sheet.json and its pages."""
    song = midi_io.load(level_midi)
    score = notation.build(song, 1, title)
    printed = {(t.name == "LH", Q(n.start, song.ticks_per_beat), n.pitch) for t in song.tracks for n in t.notes if n.printed}
    for st in score.staves:
        for voice in st.voices:
            for c in voice:
                c.fingers = [f if (st.hand == "L", c.on, p) in printed else None for f, p in zip(c.fingers, c.pitches)]
    rh = [n.start for t in song.tracks if t.name != "LH" for n in t.notes]
    left_only = {i for i, b in enumerate(score.bars) if not any(b.start <= s < b.end for s in rh)}
    xml = _with_dynamics(notation.to_musicxml(score, fingering=True), dynamics, len(score.staves), left_only)
    header = engrave.Header(title=title, level=subtitle, tempo=tempo)
    app_starts = [Q(b.start, score.tpb) for b in score.bars] + [Q(score.bars[-1].end, score.tpb)]
    return engrave.engrave_notation(xml, out_dir, stem, level, app_starts, header)


def _with_dynamics(xml: str, dynamics, staves: int, left_only=frozenset()) -> str:
    """Dynamic markings at the start of measures (index from 0), between the staves: below the right hand's, or above
    the left hand's in a measure only the left hand plays (`left_only`)."""
    lines = xml.split("\n")
    at = {i: mark for i, mark in dynamics}
    out, measure = [], -1
    for i, line in enumerate(lines):
        out.append(line)
        if line.startswith("<measure "):
            measure += 1
        mark = at.get(measure)
        if mark is None or not (line.startswith("<measure ") or line.startswith("<attributes>")):
            continue
        if line.startswith("<measure ") and i + 1 < len(lines) and lines[i + 1].startswith("<attributes>"):
            continue  # after the measure's attributes
        left = staves > 1 and measure in left_only
        staff = f"<staff>{2 if left else 1}</staff>" if staves > 1 else ""
        out.append(f'<direction placement="{"above" if left else "below"}"><direction-type><dynamics><{mark}/></dynamics>'
                   f"</direction-type>{staff}</direction>")
        del at[measure]
    return "\n".join(out)


